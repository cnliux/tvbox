package com.tvbox.app.domain

/**
 * 电视直播自动容错的触发原因。
 *
 * 区分的意义：播放器硬错误（4xx/IO/容器不支持）是确定性失败，切线路才有意义；
 * 缓冲/卡死/结束多半是 CDN 慢启动或直播流被服务端正常关闭，
 * 先原地重连同一线路比重切线路更快恢复，也避免"没坏也一路切线"。
 */
enum class LiveLineFallbackReason {
    /** 播放器硬错误：当前线路确定性不可用。 */
    Error,

    /** 缓冲超时 / 位置长时间不前进：先原地重连，多次无效再切线路。 */
    Stall,

    /** 播放结束：直播流被服务端关闭（如 FLV token 到期），先重连再考虑切线路。 */
    Ended,
}
